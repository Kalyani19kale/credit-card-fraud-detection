import streamlit as st
import numpy as np
import pickle

model = pickle.load(open("model.pkl", "rb"))
le = pickle.load(open("label_encoder.pkl", "rb"))

st.set_page_config(page_title="Fraud Detection", layout="centered")

st.title("Fraud Detection System")
st.markdown("Check whether a transaction is **Fraudulent or Legitimate**")

st.sidebar.header("About")
st.sidebar.write(
    "This app uses a Machine Learning model to detect fraudulent transactions "
    "based on transaction details."
)

st.subheader("Enter Transaction Details")

col1, col2 = st.columns(2)

with col1:
    step = st.number_input("Step (Hour)", min_value=1, max_value=743)
    type_option = st.selectbox(
        "Transaction Type",
        ["PAYMENT", "TRANSFER", "CASH_OUT", "DEBIT", "CASH_IN"]
    )
    amount = st.number_input("Amount", min_value=0.0)

with col2:
    oldbalanceOrg = st.number_input("Old Balance (Sender)", min_value=0.0)
    newbalanceOrig = st.number_input("New Balance (Sender)", min_value=0.0)
    oldbalanceDest = st.number_input("Old Balance (Receiver)", min_value=0.0)
    newbalanceDest = st.number_input("New Balance (Receiver)", min_value=0.0)

errorOrig = oldbalanceOrg - newbalanceOrig - amount
errorDest = newbalanceDest - oldbalanceDest - amount

if st.button("Predict"):

    type_encoded = le.transform([type_option])[0]

    features = np.array([[step, type_encoded, amount,
                          oldbalanceOrg, newbalanceOrig,
                          oldbalanceDest, newbalanceDest,
                          errorOrig, errorDest]])

    prediction = model.predict(features)[0]
    probability = model.predict_proba(features)[0][1]

    st.subheader("Result")

    if prediction == 1:
        st.error(f"Fraud Detected! (Risk Score: {probability:.2f})")
    else:
        st.success(f"Normal Transaction (Risk Score: {probability:.2f})")
